#!/usr/bin/env python3
"""Writes js/catalog-evolution.js: how each Pokémon evolves from the one before it.
Data: tools/pokeapi/pokemon_evolution.csv (PokeAPI). Run again after build_pokemon.py.

Each rule is keyed by the EVOLVED Pokémon's id:
  { method: 'level' | 'item' | 'trade' | 'happiness', level, item, held, time: 'any'|'day'|'night', happiness, note }
Methods this game doesn't have (spinning, special places, knowing a move, …) use a stone where the newer games
allow one, otherwise a level ("note" says so)."""
import csv, json, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
D = ROOT / 'tools' / 'pokeapi'
items = {r['id']: r['identifier'] for r in csv.DictReader(open(D / 'items.csv'))}
trig = {r['id']: r['identifier'] for r in csv.DictReader(open(D / 'evolution_triggers.csv'))}
src = (ROOT / 'js' / 'catalog-pokemon.js').read_text()
i = src.index('PP.POKEMON_CATALOG = ')
cat = json.loads(src[i + len('PP.POKEMON_CATALOG = '):src.index('];', i) + 1])
by_dex = {p['dex']: p for p in cat}
have_items = set(re.findall(r'"id":"([^"]+)"', (ROOT / 'js' / 'catalog-items.js').read_text()))

HELD_LIKE = {'linking-cord', 'metal-coat', 'kings-rock', 'dragon-scale', 'up-grade', 'dubious-disc', 'protector', 'electirizer', 'magmarizer',
             'reaper-cloth', 'prism-scale', 'razor-fang', 'razor-claw', 'deep-sea-tooth', 'deep-sea-scale', 'sachet', 'whipped-dream', 'oval-stone'}
def rule(r):
    t = trig.get(r['evolution_trigger_id'], '')
    time = r['time_of_day'] if r['time_of_day'] in ('day', 'night') else 'any'
    held = items.get(r['held_item_id'], '') if r['held_item_id'] else ''
    if held and held not in have_items: return None, -1
    if t == 'use-item':
        it = items.get(r['trigger_item_id'], '')
        if it not in have_items: return None, -1
        # one newer game lets you *use* items that are normally held during a trade or a level-up; keep the classic way
        return {'method': 'item', 'item': it, 'time': time}, 2 if it in HELD_LIKE else 5
    if t == 'trade':
        return {'method': 'trade', 'held': held, 'time': 'any'}, 4
    if t == 'level-up':
        odd = any(r[k] for k in ('location_id', 'known_move_id', 'party_species_id', 'party_type_id', 'minimum_beauty', 'relative_physical_stats', 'trade_species_id')) \
              or r['needs_overworld_rain'] == '1' or r['turn_upside_down'] == '1'
        if r['minimum_happiness'] or r['minimum_affection'] or r['known_move_type_id']:
            return {'method': 'happiness', 'happiness': int(r['minimum_happiness'] or 220), 'time': time, 'held': held}, 3 if not odd or r['known_move_type_id'] else 1
        if r['minimum_level']:
            return {'method': 'level', 'level': int(r['minimum_level']), 'time': time, 'held': held}, 3 if not odd else 1
        if held:
            return {'method': 'level', 'level': 1, 'time': time, 'held': held}, 3
        return {'method': 'level', 'level': 30, 'time': time, 'held': '', 'note': 'special in the main games; here: level 30'}, 0
    return {'method': 'level', 'level': 30, 'time': 'any', 'held': '', 'note': f'{t} in the main games; here: level 30'}, 0

best = {}
for r in csv.DictReader(open(D / 'pokemon_evolution.csv')):
    dex = int(r['evolved_species_id'])
    if dex not in by_dex: continue
    ru, score = rule(r)
    if ru is None: continue
    if r['evolved_pokemon_form_id'] or r['required_pokemon_form_id']: score -= 6     # regional-form rules come last
    key = (score, int(r['id']))
    if dex not in best or key > best[dex][0]: best[dex] = (key, ru)
out = {by_dex[d]['id']: ru for d, (_, ru) in sorted(best.items())}
for ru in out.values():
    for k in [k for k, v in ru.items() if v in ('', 'any')]: del ru[k]
js = ('// GENERATED by tools/build_evolutions.py from tools/pokeapi/pokemon_evolution.csv. Do not edit by hand:\n'
      '// change evolutions in Admin → Content → Pokémon instead. Keyed by the evolved Pokémon.\n'
      'window.PP = window.PP || {};\nPP.EVOLUTION = ' + json.dumps(out, separators=(',', ':')) + ';\n')
(ROOT / 'js' / 'catalog-evolution.js').write_text(js)
from collections import Counter
print('rules', len(out), Counter(r['method'] for r in out.values()), 'fallbacks', sum(1 for r in out.values() if 'note' in r))
